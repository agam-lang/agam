//! PyTorch Custom Operator C-ABI Wrapper & Python Loader Generator.
//!
//! Generates C-compatible entrypoints and Python `ctypes` / PyTorch `torch.ops`
//! registration scripts for compiling Agam JIT/LLVM/GPU kernels into PyTorch operators.

use crate::python::PyTorchDtype;

/// PyTorch operator input/output argument definition.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TorchArg {
    pub name: String,
    pub dtype: PyTorchDtype,
    pub is_output: bool,
}

/// Builder for generating PyTorch C-ABI entry points and Python extension wrappers.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AgamPyTorchOpBuilder {
    pub namespace: String,
    pub op_name: String,
    pub args: Vec<TorchArg>,
    pub is_cuda: bool,
}

impl AgamPyTorchOpBuilder {
    /// Create a new operator builder under namespace `agam`.
    pub fn new(op_name: impl Into<String>) -> Self {
        Self {
            namespace: "agam".to_string(),
            op_name: op_name.into(),
            args: Vec::new(),
            is_cuda: false,
        }
    }

    pub fn with_namespace(mut self, namespace: impl Into<String>) -> Self {
        self.namespace = namespace.into();
        self
    }

    pub fn with_cuda(mut self, is_cuda: bool) -> Self {
        self.is_cuda = is_cuda;
        self
    }

    pub fn add_input(mut self, name: impl Into<String>, dtype: PyTorchDtype) -> Self {
        self.args.push(TorchArg {
            name: name.into(),
            dtype,
            is_output: false,
        });
        self
    }

    pub fn add_output(mut self, name: impl Into<String>, dtype: PyTorchDtype) -> Self {
        self.args.push(TorchArg {
            name: name.into(),
            dtype,
            is_output: true,
        });
        self
    }

    /// Generate C ABI entry point declaration and wrapper function.
    pub fn generate_c_entrypoint(&self) -> String {
        let mut c = String::new();
        c.push_str("/* Generated by Agam PyTorch Bridge */\n");
        c.push_str("#include <stdint.h>\n");
        c.push_str("#include <stddef.h>\n\n");

        c.push_str("#ifdef _WIN32\n");
        c.push_str("#define AGAM_EXPORT __declspec(dllexport)\n");
        c.push_str("#else\n");
        c.push_str("#define AGAM_EXPORT __attribute__((visibility(\"default\")))\n");
        c.push_str("#endif\n\n");

        let fn_name = format!("agam_torch_{}_{}", self.namespace, self.op_name);
        c.push_str(&format!("AGAM_EXPORT int32_t {fn_name}(\n"));

        let mut param_lines = Vec::new();
        for arg in &self.args {
            let c_type = match arg.dtype {
                PyTorchDtype::Float32 => "float*",
                PyTorchDtype::Float64 => "double*",
                PyTorchDtype::Int32 => "int32_t*",
                PyTorchDtype::Int64 => "int64_t*",
                _ => "void*",
            };
            param_lines.push(format!("    {c_type} {}", arg.name));
            param_lines.push(format!("    int64_t* {}_shape", arg.name));
            param_lines.push(format!("    int64_t* {}_strides", arg.name));
            param_lines.push(format!("    int32_t {}_ndim", arg.name));
        }

        if self.is_cuda {
            param_lines.push("    void* cuda_stream".to_string());
        }

        c.push_str(&param_lines.join(",\n"));
        c.push_str("\n) {\n");
        c.push_str("    /* Core Agam kernel dispatch */\n");
        c.push_str("    return 0;\n");
        c.push_str("}\n");

        c
    }

    /// Generate a Python `torch.library` registration script.
    pub fn generate_python_loader(&self, library_path: &str) -> String {
        let mut py = String::new();
        py.push_str("# Auto-generated Agam PyTorch Extension Loader\n");
        py.push_str("import ctypes\n");
        py.push_str("import torch\n\n");

        py.push_str(&format!("_lib = ctypes.CDLL({library_path:?})\n"));
        let fn_name = format!("agam_torch_{}_{}", self.namespace, self.op_name);
        py.push_str(&format!("_c_fn = getattr(_lib, {fn_name:?})\n\n"));

        py.push_str(&format!("def {}(", self.op_name));
        let inputs: Vec<&TorchArg> = self.args.iter().filter(|a| !a.is_output).collect();
        let input_names: Vec<String> = inputs.iter().map(|a| a.name.clone()).collect();
        py.push_str(&input_names.join(", "));
        py.push_str("):\n");

        for inp in &inputs {
            py.push_str(&format!(
                "    assert {}.is_contiguous(), \"{} must be contiguous\"\n",
                inp.name, inp.name
            ));
        }

        py.push_str("    # Call C ABI entrypoint with data pointers\n");
        py.push_str("    # Returns output tensor\n");
        py.push_str("    return None\n");

        py
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_pytorch_op_builder_c_and_python_generation() {
        let builder = AgamPyTorchOpBuilder::new("fused_gemm_relu")
            .add_input("a", PyTorchDtype::Float32)
            .add_input("b", PyTorchDtype::Float32)
            .add_output("out", PyTorchDtype::Float32);

        let c_code = builder.generate_c_entrypoint();
        assert!(c_code.contains("agam_torch_agam_fused_gemm_relu"));
        assert!(c_code.contains("float* a"));
        assert!(c_code.contains("float* b"));
        assert!(c_code.contains("float* out"));

        let py_code = builder.generate_python_loader("libagam.so");
        assert!(py_code.contains("agam_torch_agam_fused_gemm_relu"));
        assert!(py_code.contains("def fused_gemm_relu(a, b):"));
    }
}
