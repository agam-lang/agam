//! Normalized pointer, keyboard, and focus events.
//!
//! Maps platform-specific window events into Agam-owned input representations.
//! No third-party types (e.g. `winit`) are exposed in this module.

use crate::scene::Point;

/// Mouse button identifiers.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MouseButton {
    /// Primary mouse button (usually Left).
    Primary,
    /// Secondary mouse button (usually Right).
    Secondary,
    /// Middle mouse button / wheel click.
    Middle,
    /// Browser/mouse back button.
    Back,
    /// Browser/mouse forward button.
    Forward,
    /// Other button indexed by driver code.
    Other(u16),
}

/// Physical state of an input element (key or button).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ElementState {
    /// Element is pressed down.
    Pressed,
    /// Element is released.
    Released,
}

impl ElementState {
    /// Returns `true` if state is `Pressed`.
    pub const fn is_pressed(&self) -> bool {
        matches!(self, Self::Pressed)
    }
}

/// Keyboard modifier keys held during an event.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Modifiers {
    /// Shift key is active.
    pub shift: bool,
    /// Control key is active.
    pub ctrl: bool,
    /// Alt / Option key is active.
    pub alt: bool,
    /// Super / Windows / Command key is active.
    pub meta: bool,
}

impl Modifiers {
    /// Returns `true` if no modifiers are active.
    pub const fn is_empty(&self) -> bool {
        !self.shift && !self.ctrl && !self.alt && !self.meta
    }
}

/// Logical key representation.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum Key {
    /// Printable character string (e.g., "a", "A", "1", "ñ").
    Character(String),
    /// Escape key.
    Escape,
    /// Enter / Return key.
    Enter,
    /// Tab key.
    Tab,
    /// Space key.
    Space,
    /// Backspace key.
    Backspace,
    /// Delete key.
    Delete,
    /// Arrow up key.
    ArrowUp,
    /// Arrow down key.
    ArrowDown,
    /// Arrow left key.
    ArrowLeft,
    /// Arrow right key.
    ArrowRight,
    /// Home key.
    Home,
    /// End key.
    End,
    /// Page Up key.
    PageUp,
    /// Page Down key.
    PageDown,
    /// Insert key.
    Insert,
    /// Function key (F1-F12+).
    F(u8),
    /// Unidentified / other key.
    Other(String),
}

/// Normalized GUI input events processed by the Agam event loop.
#[derive(Debug, Clone, PartialEq)]
pub enum GuiEvent {
    /// Pointer moved to a new window coordinate.
    PointerMoved {
        /// Logical window coordinate of the pointer.
        position: Point,
    },
    /// Pointer button pressed.
    PointerDown {
        /// Mouse button pressed.
        button: MouseButton,
        /// Logical window coordinate where the button was pressed.
        position: Point,
    },
    /// Pointer button released.
    PointerUp {
        /// Mouse button released.
        button: MouseButton,
        /// Logical window coordinate where the button was released.
        position: Point,
    },
    /// Mouse wheel or touchpad scroll delta.
    MouseWheel {
        /// Horizontal scroll delta.
        delta_x: f64,
        /// Vertical scroll delta.
        delta_y: f64,
    },
    /// Keyboard key pressed.
    KeyDown {
        /// Logical key value.
        key: Key,
        /// Optional text generated by this keypress.
        text: Option<String>,
        /// Whether this key event is an auto-repeat from being held.
        repeat: bool,
    },
    /// Keyboard key released.
    KeyUp {
        /// Logical key value.
        key: Key,
    },
    /// Modifier key state changed.
    ModifiersChanged(Modifiers),
    /// Window resized to new physical/logical dimensions.
    Resized {
        /// New width in logical pixels.
        width: u32,
        /// New height in logical pixels.
        height: u32,
        /// Current display scale factor.
        scale_factor: f64,
    },
    /// Display scale factor (DPI) changed.
    ScaleFactorChanged {
        /// New DPI scale factor.
        scale_factor: f64,
    },
    /// Native window requested to close.
    CloseRequested,
    /// Native window focus gained or lost.
    FocusChanged(bool),
    /// Window needs a redraw.
    RedrawRequested,
}
