    fn emit_gpu_ir_from_source(source: &str) -> String {
        let source_id = SourceId(0);
        let mut lexer = Lexer::new(source, source_id);
        let mut tokens = Vec::new();
        loop {
            let tok = lexer.next_token();
            let is_eof = tok.kind == TokenKind::Eof;
            tokens.push(tok);
            if is_eof {
                break;
            }
        }

        let mut parser = Parser::new(tokens);
        let module = parser.parse_module(source_id).expect("parse failed");
        let mut hir_lowering = HirLowering::new();
        let hir = hir_lowering.lower_module(&module);
        assert!(
            hir_lowering.diagnostics.is_empty(),
            "unexpected HIR diagnostics: {:?}",
            hir_lowering.diagnostics
        );

        let mut mir_lowering = MirLowering::new();
        let mir = mir_lowering.lower_module(&hir);
        emit_gpu_module(&mir).expect("expected gpu module")
    }

